// Bundles src/ into worker.js, the file Cloudflare deploys (wrangler.jsonc "main").
// worker.js is committed; CI fails if it is out of date with src/.
import { build } from "esbuild";

await build({
  entryPoints: ["src/index.js"],
  outfile: "worker.js",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  charset: "utf8",
  loader: { ".html": "text" },
  banner: { js: "// GENERATED by build.mjs from src/ — do not edit. Change src/ and run `npm run build`." },
  logLevel: "warning",
});
